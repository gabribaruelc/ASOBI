-- Quem pediu para ser avisado sobre um produto. Só o e-mail do adulto responsável, nunca
-- dado de criança. consented_at é o registro do consentimento (LGPD); o descadastro apaga a linha.
CREATE TABLE subscriptions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(254) NOT NULL,
    product_id        BIGINT       NOT NULL,
    alert_type        VARCHAR(20)  NOT NULL,
    unsubscribe_token VARCHAR(64)  NOT NULL UNIQUE,
    consented_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_notified_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_subscriptions_email_product_type UNIQUE (email, product_id, alert_type)
);

CREATE INDEX idx_subscriptions_product_type ON subscriptions (product_id, alert_type);
