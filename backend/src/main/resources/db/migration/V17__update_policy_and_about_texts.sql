- Processar o pedido, emitir a nota fiscal, entregar a compra e prestar atendimento (execução do contrato).
- Enviar e-mails sobre o pedido: confirmação, pagamento, envio e um único lembrete se o pagamento não foi concluído (execução do contrato e legítimo interesse).
- Cumprir obrigações legais e fiscais, como guardar os registros de venda.
- Enviar a newsletter e os avisos do avise-me, só para quem pediu (consentimento).
- Publicar avaliações, que só aparecem depois de aprovadas pela nossa equipe.
