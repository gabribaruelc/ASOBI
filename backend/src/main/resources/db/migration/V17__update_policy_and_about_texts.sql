- Mercado Pago: processamento do pagamento.
- Melhor Envio, Correios e transportadoras: cálculo do frete e entrega.
- Resend: envio dos e-mails.
- Supabase, Google Cloud e Cloudflare: hospedagem do site, do banco de dados e do login.
- Google: login com a conta Google, quando você escolhe essa opção.
Alguns desses fornecedores podem guardar dados em servidores fora do Brasil, sempre com as garantias previstas na LGPD. Também podemos informar dados a autoridades quando a lei exigir.

