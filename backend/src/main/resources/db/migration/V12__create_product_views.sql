-- Visualizações da ficha de cada produto, somadas por dia (dashboard do painel).
-- É só um contador: não guarda quem viu.
CREATE TABLE product_views (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    view_date  DATE   NOT NULL,
    views      BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_product_views_product_date UNIQUE (product_id, view_date)
);

CREATE INDEX idx_product_views_date ON product_views (view_date);
CREATE INDEX idx_orders_paid_at ON orders (paid_at);
