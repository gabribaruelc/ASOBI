A loja é feita para adultos que compram para crianças. Não pedimos nem guardamos nome, idade, foto, escola ou qualquer outro dado que identifique uma criança. A única informação ligada a ela é a faixa etária do jogo escolhido, que não identifica ninguém.
Seguimos o artigo 14 da LGPD: qualquer tratamento de dados de crianças deve ser feito no melhor interesse delas e com o consentimento específico de um dos pais ou do responsável legal. Como não precisamos desses dados para vender, não coletamos.
Pedimos que crianças não usem os formulários do site (compra, avaliação, newsletter e avise-me). Se percebermos que recebemos dados de uma criança, por exemplo em uma avaliação, apagamos esses dados.

# Quais dados coletamos
- Na compra: nome, e-mail, telefone e endereço de entrega do adulto que compra, e os jogos do pedido.
- Ao entrar com a conta Google: o nome e o e-mail da conta, para mostrar seus pedidos em Meus pedidos. Comprar sem cadastro continua possível.
