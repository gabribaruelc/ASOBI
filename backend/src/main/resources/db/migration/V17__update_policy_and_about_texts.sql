- Newsletter e avise-me: até você se descadastrar pelo link que vem em todo e-mail.
- Avaliações: enquanto estiverem publicadas, ou até você pedir a exclusão.

# Segurança
Os dados ficam em serviços com acesso protegido e conexão criptografada. Só a equipe da ASOBI acessa o painel da loja, com login protegido.

# Seus direitos
Você pode, a qualquer momento: confirmar se tratamos seus dados, acessar, corrigir, pedir a exclusão, revogar o consentimento (por exemplo, sair da newsletter), pedir a portabilidade e saber com quem compartilhamos. Basta falar com a gente pelos canais da página Fale Conosco. Você também pode reclamar à Autoridade Nacional de Proteção de Dados (ANPD).

