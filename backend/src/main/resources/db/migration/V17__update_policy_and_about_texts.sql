- Na newsletter: só o e-mail.
- No avise-me (volta ao estoque, promoção ou últimas unidades): o e-mail e o jogo escolhido.
- No cálculo do frete: o CEP de entrega.
Não recebemos nem guardamos dados de cartão. O pagamento é feito na página do Mercado Pago, e o que você digita lá segue a política de privacidade do Mercado Pago.

