-- Envio da newsletter pelo painel.

-- Link de descadastro de cada inscrito. Fica vazio nas inscrições antigas até o primeiro
-- envio (o token é gerado no Java, igual nos dois bancos).
ALTER TABLE newsletter_subscribers ADD COLUMN unsubscribe_token VARCHAR(64);
ALTER TABLE newsletter_subscribers
    ADD CONSTRAINT uq_newsletter_subscribers_unsubscribe_token UNIQUE (unsubscribe_token);

-- Uma newsletter escrita no painel. started_at nulo = rascunho; depois do primeiro envio
-- o texto não muda mais e só recebe quem já estava inscrito nesse momento.
CREATE TABLE newsletter_campaigns (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject      VARCHAR(200)   NOT NULL,
    body         VARCHAR(20000) NOT NULL,
    button_label VARCHAR(60),
    button_url   VARCHAR(500),
    created_by   VARCHAR(254)   NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at   TIMESTAMP WITH TIME ZONE
);

-- Quem já recebeu cada newsletter: o envio continua de onde parou sem repetir ninguém, e
-- sent_at conta o limite diário do Resend. Some junto com o inscrito no descadastro.
CREATE TABLE newsletter_deliveries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id   BIGINT NOT NULL REFERENCES newsletter_campaigns (id) ON DELETE CASCADE,
    subscriber_id BIGINT NOT NULL REFERENCES newsletter_subscribers (id) ON DELETE CASCADE,
    sent_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_newsletter_deliveries_campaign_subscriber UNIQUE (campaign_id, subscriber_id)
);

CREATE INDEX idx_newsletter_deliveries_sent_at ON newsletter_deliveries (sent_at);
CREATE INDEX idx_newsletter_deliveries_subscriber ON newsletter_deliveries (subscriber_id);
