# Quem é responsável pelos seus dados
A ASOBI é a controladora dos dados tratados nesta loja. A razão social e o CNPJ estão no rodapé do site. Para qualquer assunto sobre privacidade, fale com a gente pelos canais da página Fale Conosco.

